#!/usr/bin/env python3
"""Generate the RPC/CLI reference documentation from a running node.

The node exposes the text of every `RPCHelpMan` entry through the `help` RPC
command. This script renders that text into deterministic Markdown pages below
`docs/node-manual/rpc-cli/categories/`, so the reference never drifts away
from the binary it documents.

Usage:

    # Generate the pages with a temporary regtest node.
    python3 contrib/devtools/gen-rpc-docs.py

    # Verify that the committed pages still match the binary.
    python3 contrib/devtools/gen-rpc-docs.py --check

    # Use an already running node instead of spawning one.
    python3 contrib/devtools/gen-rpc-docs.py --rpcuser=user --rpcpassword=pass

The script has no third-party dependencies. It always terminates the node it
spawns, so it never leaves a background daemon behind.
"""

from __future__ import annotations

import argparse
import contextlib
import difflib
import re
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT_DIR = REPO_ROOT / "docs" / "node-manual" / "rpc-cli" / "categories"
DEFAULT_DEFID = REPO_ROOT / "build" / "src" / "defid"
DEFAULT_DEFI_CLI = REPO_ROOT / "build" / "src" / "defi-cli"

GENERATED_NOTICE = (
    "<!-- This file is generated by `contrib/devtools/gen-rpc-docs.py`. "
    "Do not edit it manually. -->"
)

# `defi-cli help` prints one line per command, grouped by category headers.
CATEGORY_HEADER = re.compile(r"^== (.+) ==$")
COMMAND_LINE = re.compile(r"^([a-z][a-z0-9_]*)\b")


def repo_relative(path: Path) -> str:
    """Return a path relative to the repository root when possible."""
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


class GeneratorError(RuntimeError):
    """Raised when the extraction cannot be completed."""


def find_free_port() -> int:
    """Return a free TCP port on the loopback interface."""
    with contextlib.closing(socket.socket(socket.AF_INET, socket.SOCK_STREAM)) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def slugify(name: str) -> str:
    """Turn a category name into a stable file name."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug or "misc"


class Node:
    """A `defid` instance used to read the RPC help text.

    The node is either spawned by this class or supplied by the caller through
    the command line. In the spawned case the node is always stopped again.
    """

    def __init__(
        self,
        defid: Path,
        defi_cli: Path,
        chain: str,
        rpc_user: str,
        rpc_password: str,
        rpc_port: int,
        proc: subprocess.Popen | None = None,
        datadir: Path | None = None,
    ) -> None:
        self.defid = defid
        self.defi_cli = defi_cli
        self.chain = chain
        self.rpc_user = rpc_user
        self.rpc_password = rpc_password
        self.rpc_port = rpc_port
        self.proc = proc
        self.datadir = datadir

    @property
    def cli_args(self) -> list[str]:
        """Command line arguments shared by all `defi-cli` invocations."""
        return [
            f"-{self.chain}",
            f"-rpcuser={self.rpc_user}",
            f"-rpcpassword={self.rpc_password}",
            f"-rpcport={self.rpc_port}",
        ]

    @classmethod
    def spawn(
        cls,
        defid: Path,
        defi_cli: Path,
        chain: str = "regtest",
        rpc_user: str = "rpcdocs",
        rpc_password: str = "rpcdocs",
        timeout: int = 120,
    ) -> "Node":
        """Start a temporary node and wait until its RPC interface answers."""
        if not defid.is_file():
            raise GeneratorError(
                f"daemon binary not found: {defid}\n"
                "Build the node first (for example with `./make.sh build`) or pass --defid."
            )
        if not defi_cli.is_file():
            raise GeneratorError(
                f"cli binary not found: {defi_cli}\n"
                "Build the node first (for example with `./make.sh build`) or pass --defi-cli."
            )

        datadir = Path(tempfile.mkdtemp(prefix="defi-rpc-docs-"))
        rpc_port = find_free_port()
        p2p_port = find_free_port()
        args = [
            str(defid),
            f"-{chain}",
            f"-datadir={datadir}",
            f"-rpcuser={rpc_user}",
            f"-rpcpassword={rpc_password}",
            f"-rpcport={rpc_port}",
            f"-port={p2p_port}",
            "-listen=0",
            "-dnsseed=0",
            "-discover=0",
            "-printtoconsole=0",
            "-server=1",
            # Disable the auxiliary servers, they are not needed for the
            # extraction and would collide with other nodes on the machine.
            "-ethrpcport=-1",
            "-wsport=-1",
            "-ethsubscription=0",
            "-oceanarchive=0",
            "-oceanarchiveserver=0",
        ]
        logfile = datadir / "defid.log"
        with open(logfile, "wb") as log:
            proc = subprocess.Popen(args, stdout=log, stderr=subprocess.STDOUT)
        node = cls(defid, defi_cli, chain, rpc_user, rpc_password, rpc_port, proc, datadir)
        try:
            node.wait_until_ready(timeout)
        except Exception:
            node.stop()
            raise
        return node

    def wait_until_ready(self, timeout: int) -> None:
        """Poll the RPC interface until the node answers."""
        deadline = time.time() + timeout
        last_error = ""
        while time.time() < deadline:
            if self.proc is not None and self.proc.poll() is not None:
                raise GeneratorError(
                    f"the node exited with code {self.proc.returncode}; "
                    f"see {self.datadir / 'defid.log' if self.datadir else 'the log file'}"
                )
            try:
                self.run_cli(["getblockcount"])
                return
            except GeneratorError as error:
                last_error = str(error)
                time.sleep(0.5)
        raise GeneratorError(f"the node did not become ready within {timeout}s: {last_error}")

    def run_cli(self, args: list[str]) -> str:
        """Run a `defi-cli` command and return its standard output."""
        command = [str(self.defi_cli), *self.cli_args, *args]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            message = (result.stderr or result.stdout).strip()
            raise GeneratorError(f"`{' '.join(command)}` failed: {message}")
        return result.stdout

    def stop(self) -> None:
        """Stop the node and remove its data directory."""
        if self.proc is not None and self.proc.poll() is None:
            with contextlib.suppress(GeneratorError):
                self.run_cli(["stop"])
            try:
                self.proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                self.proc.terminate()
                with contextlib.suppress(subprocess.TimeoutExpired):
                    self.proc.wait(timeout=10)
                if self.proc.poll() is None:
                    self.proc.kill()
                    with contextlib.suppress(subprocess.TimeoutExpired):
                        self.proc.wait(timeout=10)
        self.proc = None
        if self.datadir is not None:
            shutil.rmtree(self.datadir, ignore_errors=True)
            self.datadir = None


def parse_categories(help_output: str) -> dict[str, list[str]]:
    """Split the output of `defi-cli help` into categories and commands."""
    categories: dict[str, list[str]] = {}
    current: str | None = None
    for raw_line in help_output.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        header = CATEGORY_HEADER.match(line)
        if header:
            current = header.group(1)
            categories.setdefault(current, [])
            continue
        if current is None:
            continue
        match = COMMAND_LINE.match(line)
        if match:
            name = match.group(1)
            if name not in categories[current]:
                categories[current].append(name)
    return {name: sorted(commands) for name, commands in sorted(categories.items())}


def collect_help_texts(node: Node, categories: dict[str, list[str]]) -> dict[str, str]:
    """Read the full help text of every command."""
    texts: dict[str, str] = {}
    for commands in categories.values():
        for command in commands:
            texts[command] = node.run_cli(["help", command]).strip("\n")
    return texts


def render_category(category: str, commands: list[str], texts: dict[str, str]) -> str:
    """Render the Markdown page of a single RPC category."""
    lines = [
        f"# {category} RPC commands",
        "",
        GENERATED_NOTICE,
        "",
        f"The `{category}` category of the DeFiChain JSON-RPC interface exposes "
        f"{len(commands)} command{'s' if len(commands) != 1 else ''}. The text below is the "
        "help output of the node itself, so it matches the binary that generated this page.",
        "",
        "For the complete interface, see the "
        "[RPC and CLI reference](../index.md).",
        "",
    ]
    for command in commands:
        lines.append(f"## {command}")
        lines.append("")
        lines.append("```text")
        lines.append(texts[command].rstrip())
        lines.append("```")
        lines.append("")
    return "\n".join(lines)


def render_category_index(categories: dict[str, list[str]]) -> str:
    """Render the index page that lists every RPC category."""
    total = sum(len(commands) for commands in categories.values())
    lines = [
        "# RPC command categories",
        "",
        GENERATED_NOTICE,
        "",
        f"The node exposes {total} JSON-RPC commands in {len(categories)} categories. "
        "The list below is generated from the help output of the node.",
        "",
        "| Category | Commands | Page |",
        "| --- | --- | --- |",
    ]
    for category, commands in categories.items():
        lines.append(
            f"| {category} | {len(commands)} | [{slugify(category)}.md]({slugify(category)}.md) |"
        )
    lines.append("")
    return "\n".join(lines)


def build_pages(node: Node) -> dict[str, str]:
    """Extract the RPC reference and render all pages."""
    categories = parse_categories(node.run_cli(["help"]))
    if not categories:
        raise GeneratorError("no RPC categories found in the help output")
    texts = collect_help_texts(node, categories)
    pages: dict[str, str] = {}
    for category, commands in categories.items():
        pages[f"{slugify(category)}.md"] = render_category(category, commands, texts)
    pages["index.md"] = render_category_index(categories)
    return pages


def compare_pages(expected: dict[str, str], output_dir: Path) -> list[str]:
    """Compare the rendered pages with the committed ones."""
    problems: list[str] = []
    committed = {path.name for path in output_dir.glob("*.md")} if output_dir.is_dir() else set()
    for name in sorted(set(expected) | committed):
        if name not in expected:
            problems.append(f"{name}: not generated any more, remove the file")
            continue
        if name not in committed:
            problems.append(f"{name}: missing, run the generator")
            continue
        current = (output_dir / name).read_text(encoding="utf-8")
        if current != expected[name]:
            diff = difflib.unified_diff(
                current.splitlines(keepends=True),
                expected[name].splitlines(keepends=True),
                fromfile=f"committed/{name}",
                tofile=f"generated/{name}",
            )
            problems.append(f"{name}: out of date\n" + "".join(diff))
    return problems


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate the RPC/CLI reference documentation from a node.",
    )
    parser.add_argument(
        "--defid",
        type=Path,
        default=DEFAULT_DEFID,
        help="path to the defid binary (default: build/src/defid)",
    )
    parser.add_argument(
        "--defi-cli",
        type=Path,
        default=DEFAULT_DEFI_CLI,
        help="path to the defi-cli binary (default: build/src/defi-cli)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="directory that receives the generated pages",
    )
    parser.add_argument(
        "--chain",
        default="regtest",
        help="chain of the node that is queried (default: regtest)",
    )
    parser.add_argument(
        "--rpcuser",
        default="rpcdocs",
        help="RPC user of an already running node",
    )
    parser.add_argument(
        "--rpcpassword",
        default="rpcdocs",
        help="RPC password of an already running node",
    )
    parser.add_argument(
        "--rpcport",
        type=int,
        default=None,
        help="RPC port of an already running node; without it a node is spawned",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write anything, exit with 1 when the committed pages are out of date",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=120,
        help="seconds to wait for a spawned node to become ready (default: 120)",
    )
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)

    if args.rpcport is not None:
        node = Node(
            args.defid,
            args.defi_cli,
            args.chain,
            args.rpcuser,
            args.rpcpassword,
            args.rpcport,
        )
        try:
            pages = build_pages(node)
        finally:
            node.stop()
    else:
        node = Node.spawn(
            args.defid,
            args.defi_cli,
            chain=args.chain,
            rpc_user=args.rpcuser,
            rpc_password=args.rpcpassword,
            timeout=args.timeout,
        )
        try:
            pages = build_pages(node)
        finally:
            node.stop()

    output_dir = args.output_dir
    if args.check:
        problems = compare_pages(pages, output_dir)
        if problems:
            print("The RPC documentation is out of date:", file=sys.stderr)
            for problem in problems:
                print(problem, file=sys.stderr)
            print(
                "Run `python3 contrib/devtools/gen-rpc-docs.py` to regenerate it.",
                file=sys.stderr,
            )
            return 1
        print(f"The RPC documentation in {repo_relative(output_dir)} is up to date.")
        return 0

    output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in pages.items():
        path = output_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
    for path in output_dir.glob("*.md"):
        if path.name not in pages:
            path.unlink()
    print(
        f"Wrote {len(pages)} pages to {repo_relative(output_dir)} "
        f"({sum(len(content) for content in pages.values())} bytes)."
    )
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except GeneratorError as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(2)
